#!/usr/bin/env python3
"""Write sky-table.glsl: the brighter stars and the familiar constellations, projected
onto the plane the night shader draws them on.

The chart is a stereographic projection centered on the north ecliptic pole, as Dürer's
1515 star maps are.  Unlike his, it's seen from inside the sphere, as the sky is, so that
the shapes aren't mirrored: longitude runs clockwise, and the ecliptic is the unit circle.
Stars are (x, y, magnitude, B-V color index), and lines are (x1, y1, x2, y2).

Input is stars.6.json and constellations.lines.json from d3-celestial:
    https://github.com/ofrohn/d3-celestial/tree/master/data
Usage: sky-table.py DATA-DIR > sky-table.glsl
"""
import json
import math
import sys

MAGNITUDE_LIMIT = 4.4
RADIUS_LIMIT = 3.3          # the ecliptic is at 1; this is about 55 degrees south of it
OBLIQUITY = math.radians(23.4392911)
# Trimmed from the ends of each constellation line, so that lines stop short of the stars.
LINE_GAP = 0.016
# Just the shapes that people know, or the rest of the chart turns into scratches.
CONSTELLATIONS = "UMa UMi Cas Cyg Lyr Aql Boo Ori CMa Leo Sco Gem Tau Sgr Peg".split()

