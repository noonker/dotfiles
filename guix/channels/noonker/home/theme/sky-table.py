def chart(ra_degrees, dec_degrees):
    """(x, y) on the chart for a J2000 position; d3-celestial's right ascension runs -180..180."""
    ra, dec = math.radians(ra_degrees), math.radians(dec_degrees)
    x = math.cos(dec) * math.cos(ra)
    y = math.cos(dec) * math.sin(ra)
    z = math.sin(dec)
    # Equatorial to ecliptic.
    ey = y * math.cos(OBLIQUITY) + z * math.sin(OBLIQUITY)
    ez = -y * math.sin(OBLIQUITY) + z * math.cos(OBLIQUITY)
    longitude = math.atan2(ey, x)
    colatitude = math.acos(max(-1.0, min(1.0, ez)))
    radius = math.tan(colatitude / 2.0)
    return radius * math.cos(longitude), -radius * math.sin(longitude)


def within(point):
    return math.hypot(*point) <= RADIUS_LIMIT


def number(value):
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return text if "." in text else text + ".0"


def main(directory):
    with open(f"{directory}/stars.6.json") as file:
        features = json.load(file)["features"]
    stars = []
    for feature in features:
        magnitude = feature["properties"]["mag"]
        if magnitude > MAGNITUDE_LIMIT:
            continue
        point = chart(*feature["geometry"]["coordinates"])
        if within(point):
            color = float(feature["properties"].get("bv") or 0.6)
            stars.append((magnitude, point, color))
    stars.sort(key=lambda star: star[0])

    with open(f"{directory}/constellations.lines.json") as file:
        features = json.load(file)["features"]
    lines = []
    for feature in features:
        if feature["id"] not in CONSTELLATIONS:
            continue
        for strip in feature["geometry"]["coordinates"]:
            points = [chart(*position) for position in strip]
            for a, b in zip(points, points[1:]):
                length = math.hypot(b[0] - a[0], b[1] - a[1])
                if length <= 2.0 * LINE_GAP or not (within(a) and within(b)):
                    continue
                trim = LINE_GAP / length
                lines.append((a[0] + (b[0] - a[0]) * trim, a[1] + (b[1] - a[1]) * trim,
                              b[0] - (b[0] - a[0]) * trim, b[1] - (b[1] - a[1]) * trim))

    print("// Generated by sky-table.py; don't edit.")
    print(NOTICE)
    print(f"const int STAR_COUNT = {len(stars)};")
    print(f"const vec4 STARS[{len(stars)}] = vec4[{len(stars)}](")
    print(",\n".join(f"vec4({number(p[0])},{number(p[1])},{number(m)},{number(c)})"
                     for m, p, c in stars))
    print(");")
    print(f"const int LINE_COUNT = {len(lines)};")
    print(f"const vec4 LINES[{len(lines)}] = vec4[{len(lines)}](")
    print(",\n".join("vec4(" + ",".join(number(v) for v in line) + ")" for line in lines))
    print(");")
    print(f"{len(stars)} stars, {len(lines)} lines", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
